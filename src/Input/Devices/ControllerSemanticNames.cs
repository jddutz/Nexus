namespace Nexus.Input.Devices;

/// <summary>Defines the semantic-name vocabulary used for recognized Silk.NET gamepad controls.</summary>
public static class ControllerSemanticNames
{
    /// <summary>Bottom face control, conventionally Silk.NET A.</summary>
    public const string FaceBottom = nameof(FaceBottom);

    /// <summary>Right face control, conventionally Silk.NET B.</summary>
    public const string FaceRight = nameof(FaceRight);

    /// <summary>Left face control, conventionally Silk.NET X.</summary>
    public const string FaceLeft = nameof(FaceLeft);

    /// <summary>Top face control, conventionally Silk.NET Y.</summary>
    public const string FaceTop = nameof(FaceTop);

    /// <summary>Left shoulder bumper.</summary>
    public const string LeftBumper = nameof(LeftBumper);

    /// <summary>Right shoulder bumper.</summary>
    public const string RightBumper = nameof(RightBumper);

    /// <summary>Left thumbstick press control.</summary>
    public const string LeftStickClick = nameof(LeftStickClick);

    /// <summary>Right thumbstick press control.</summary>
    public const string RightStickClick = nameof(RightStickClick);

    /// <summary>Left thumbstick two-axis analog input.</summary>
    public const string LeftStick = nameof(LeftStick);

    /// <summary>Right thumbstick two-axis analog input.</summary>
    public const string RightStick = nameof(RightStick);

    /// <summary>Left one-direction trigger analog input.</summary>
    public const string LeftTrigger = nameof(LeftTrigger);

    /// <summary>Right one-direction trigger analog input.</summary>
    public const string RightTrigger = nameof(RightTrigger);

    /// <summary>Directional-pad up control.</summary>
    public const string DPadUp = nameof(DPadUp);

    /// <summary>Directional-pad right control.</summary>
    public const string DPadRight = nameof(DPadRight);

    /// <summary>Directional-pad down control.</summary>
    public const string DPadDown = nameof(DPadDown);

    /// <summary>Directional-pad left control.</summary>
    public const string DPadLeft = nameof(DPadLeft);

    /// <summary>Back or select menu control.</summary>
    public const string Back = nameof(Back);

    /// <summary>Start or menu control.</summary>
    public const string Start = nameof(Start);

    /// <summary>System home control.</summary>
    public const string Home = nameof(Home);
}
